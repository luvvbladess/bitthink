import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
import React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import ReactMarkdown from 'react-markdown';
import remarkGfm from 'remark-gfm';

const source = fs.readFileSync(new URL('./richAnswerData.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
const { parseAnswerCard, safeCardUrl, copyableAnswer, remarkAnswerCallouts } = await import('data:text/javascript;base64,' + Buffer.from(compiled).toString('base64'));
assert.equal(parseAnswerCard('not json'), null);
assert.equal(parseAnswerCard('[]'), null);
assert.equal(parseAnswerCard('{}'), null);
assert.equal(parseAnswerCard(' '.repeat(16001)), null);
for (const unsafe of ['javascript:alert(1)', 'data:text/html,x', '//evil.test/a', 'https://user:pass@example.com']) assert.equal(safeCardUrl(unsafe), undefined);
const card = parseAnswerCard(JSON.stringify({ title: 'Вариант', description: '<script>alert(1)</script>', url: 'javascript:alert(1)', image: '/uploads/test.png', unknown: 'drop' }));
assert.equal(card.url, undefined);
assert.equal(card.image, '/uploads/test.png');
assert.equal(card.unknown, undefined);
assert.equal(safeCardUrl('/uploads//evil.test', true), undefined);
const payload = JSON.stringify({ title: 'Инструмент', description: 'Подходит для задачи.', url: 'https://example.com/tool' });
const copy = copyableAnswer('Сравнение\n\n```bitthink-card\n' + payload + '\n```\n\n> [!TIP] Совет\n> Начните с примера.');
assert.ok(copy.includes('https://example.com/tool') && !copy.includes('bitthink-card') && !copy.includes('[!TIP]'));
const html = renderToStaticMarkup(React.createElement(ReactMarkdown, { remarkPlugins: [remarkGfm, remarkAnswerCallouts], children: '> [!WARNING] Перед запуском\n> Сохраните **копию** и [инструкцию](https://example.com).\n\n> Обычная цитата\n\n- [x] Проверка\n- [ ] Публикация' }));
assert.ok(html.includes('data-callout="warning"') && html.includes('Перед запуском'));
assert.ok(!html.includes('[!WARNING]'));
assert.ok(html.includes('<strong>копию</strong>') && html.includes('href="https://example.com"'));
assert.ok(html.includes('<blockquote>\n<p>Обычная цитата</p>'));
assert.ok(html.includes('checked=""'));
console.log('PASS rich cards: URL safety, bounded payloads, copy, callouts, links, plain quotes and checklists');
