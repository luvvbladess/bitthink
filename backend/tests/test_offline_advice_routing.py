import pytest
from app.services.orchestrator_policy import bounded_text_task


@pytest.mark.parametrize('text',[
    'Как подготовиться к разговору с руководителем о повышении зарплаты? Дай пять конкретных шагов. Без поиска в интернете.',
    'Как подготовиться к разговору с коллегой о распределении задач? Без интернета, три шага.',
    'Как подготовиться к разговору с клиентом о переносе встречи? Без интернета.',
])
def test_explicit_offline_conversation_advice_is_a_text_answer(text):
    assert bounded_text_task(text)


@pytest.mark.parametrize('text',[
    'Как подготовиться к разговору с руководителем? Найди актуальные советы.',
    'Как подготовиться к разговору с врачом о диагнозе? Без интернета.',
    'Как подготовиться к разговору по договору? Без интернета.',
    'Как подготовиться к разговору? Прочитай прикреплённый файл. Без интернета.',
    'Как подготовиться к разговору? Без интернета. Отправь письмо клиенту.',
    'Как подготовиться к разговору? Без интернета. Создай PDF.',
    'Как подготовиться к разговору? Без интернета. Сначала зайди на сервер.',
    'Как подготовиться к разговору? Без интернета. Учти актуальные цены.',
    'Как подготовиться к разговору? Без интернета. Объясни формальное доказательство.',
])
def test_unknown_expert_or_action_requests_keep_existing_route(text):
    assert not bounded_text_task(text)
