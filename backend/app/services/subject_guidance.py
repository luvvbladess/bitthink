_CODE = re.compile(r'(?i)\b(?:код\w*|программ\w*|python|typescript|javascript|sql|pytest|react|'
                   r'рефактор\w*|отлад\w*|компил\w*|traceback|rust|csharp|cortex[ -]?m[0-9]\w*|'
                   r'enfusion|enforce\s+script|dotnet|cmsis)\b|(?<!\w)(?:[cс]\+\+|c#|\.net)(?!\w)')
_CPP = re.compile(r'(?i)(?<!\w)[cс]\+\+(?:\d{2})?(?!\w)')


def subject_for_query(text):
    if _TRANSFORM.search(text or ''):
        return None
    if _CODE.search(text or '') or _CPP.search(text or ''):
        return 'code'
    if _ENGINEERING.search(text or ''):
        return 'engineering'
    if _HUMANITIES.search(text or ''):
        return 'humanities'
    if _HISTORY.search(text or ''):
        return 'history'
    return None


def needs_subject_reasoning(text):
    subject = subject_for_query(text)
    quantitative = bool(re.search(r'\d|(?i:рассчита\w*|вычисл\w*|расч[её]т\w*|спроектиру\w*)', text or ''))
    return bool((subject == 'engineering' and quantitative) or (subject and _ANALYTIC.search(text or '')))


