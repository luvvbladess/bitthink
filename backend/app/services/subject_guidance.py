def subject_note(text):
    subject = subject_for_query(text)
    note = _NOTES.get(subject, '')
    if subject != 'code':
        return note
    note += (' Сначала сверь контракт: граничные случаи, переполнение, мутацию входа, '
             'сложность и поведение при ошибке. До ответа мысленно проследи эти случаи. '
             'Не заменяй исполняемый код многоточиями. Если просят только код или JSON, '
             'не дописывай объяснение после него.')
    if _CPP.search(text or ''):
        note += (' В C++ беззнаковое вычитание индексов может переполниться до проверки: '
                 'проверяй границу до вычисления разности. Не используй underflow size_t как '
                 'способ выразить отрицательную границу. Проверь инварианты контейнера и '
                 'валидность итераторов перед чтением; constexpr требует константного выражения.')
    if re.search(r'(?i)cortex[ -]?m0\b|armv6[ -]?m\b', text or ''):
        note += (' Учитывай именно ARMv6-M: у Cortex-M0 нет FPU, LDREX/STREX и BASEPRI; '
                 'не переноси инструкции и регистры M3/M4. CMSIS зависит от целевого ядра. '
                 'Сохраняй состояние масок прерываний; volatile не гарантирует атомарность. '
                 'Проверка компиляцией для хоста не проверяет поддержку инструкций MCU.')
    if re.search(r'(?i)enfusion|enforce\s+script', text or ''):
        note += (' Enforce Script имеет собственные синтаксис, владение и жизненный цикл. '
                 'Не переноси API SQF, C# или DayZ в Arma Reforger. '
                 'Сверяй неизвестные API с документацией нужного движка. '
                 'Учитывай повторную регистрацию callback, снятие подписок и время жизни объектов. '
                 'Проверенная справка Arma Reforger API (2026-11-04): '
                 'ScriptComponent имеет protected void OnDelete(IEntity owner), не EOnDelete. '
                 'Другие события компонента включают EOnInit(IEntity owner) и EOnFrame(IEntity owner, float timeSlice). '
                 'Источник: https://community.bistudio.com/wikidata/external-data/arma-reforger/EnfusionScriptAPIPublic/interfaceScriptComponent.html. '
                 'ScriptCallQueue: CallLater(func fn, int delay, bool repeat), Remove(func fn); '
                 'ScriptInvoker: Insert(callback), Remove(callback). '
                 'Не переносить эти сигнатуры на другие классы или движки.')
    if re.search(r'(?i)rust', text or ''):
        note += (' В Rust учитывай ownership и borrowing, не усиливай generic bounds без необходимости. '
                 'При контракте «ошибка не меняет состояние» сначала проверь все изменения, '
                 'затем применяй их; учитывай отсутствующие элементы и нулевые значения.')
    if re.search(r'(?i)async|await|асинхрон|cancellation|отмен', text or ''):
        note += (' В асинхронном коде проверь предел параллелизма, порядок результатов, '
                 'распространение исходной ошибки и отмены, завершение всех начатых операций. '
                 'Различай отмену вызывающим и собственный таймаут; освобождай ресурсы. '
                 'Не превращай произвольную ошибку операции или её очистки в TimeoutException '
                 'из-за сработавшего таймера: преобразуется только отмена по собственному таймауту. '
                 'Избегай лишних гонок Task.WhenAny, если достаточно дождаться кооперативной операции '
                 'со связанным токеном. Проверь синхронные ошибки, гонки завершения и границы '
                 'допустимого диапазона таймеров; не вводи произвольный предел int.MaxValue миллисекунд.')
    return note
