"""Local venue selection: bounded research with the user's original constraints."""
import re

VENUE_RULES = """Подбор мест для посещения: сохрани город, район, кухню, бюджет, размер порций и остальные ограничения пользователя.
При «недорого» главным критерием являются цены нужных блюд и стоимость сытного заказа на человека/двоих, а не общий средний чек или популярность. Если численного бюджета нет, сравни нижний ценовой сегмент найденной выборки и назови принятый ориентир; не объявляй его бюджетом пользователя. Дорогие варианты исключи из основной рекомендации.
Рассмотри разумную широкую выборку (обычно 8–12 кандидатов, если доступны), затем предложи 5–8 подходящих вариантов, если они подтверждены. Не добивай количество неподходящими местами. Если нужны разные кухни, представь каждую, а не только раменные.
Сопоставь конкретный филиал на Яндекс Картах/2ГИС (или других местных картах) с официальным меню: адрес, район/метро, цена конкретного основного блюда, размер/вес порции если указан, стоимость реалистичного заказа, актуальные отзывы о порциях и качестве. Общий обзор — источник кандидатов, не доказательство текущей цены. Ищи карты и меню отдельными запросами, открывай найденные страницы. Не подменяй посещение карточки карты поисковым сниппетом; если карта блокируется, явно обозначь ограничение и продолжи проверять меню и другие доступные источники. Не выдумывай рейтинг, вес, время пешком, адрес или ссылку карточки.
После первого прохода адресно закрой пробелы по наиболее подходящим кандидатам. Одной статьи или списка ссылок недостаточно. Ссылки на прочитанные меню и карточки ставь рядом с соответствующим местом; число источников не означает число проверенных мест.
В итоговой подборке сравни одинаковые критерии: место/кухня, конкретный заказ и цена, расположение, почему подходит и что не подтверждено. Сначала самые доступные подходящие варианты. Проверенные факты отделяй от оценки. Если цен нет, место остаётся непроверенным кандидатом, а не рекомендацией «недорого». Не перекладывай основную проверку цен на пользователя и не рекомендуй дорогой вариант с припиской «уточните меню»."""

_VENUE = re.compile(r'(?i)ресторан|рестик|кафе|кофейн|рамен|рам[её]н|пельменн|столов[а-я]*|бар(?:ы|ов|е)?\b|где\s+(?:поесть|поужинать|позавтракать|пообедать)|мест[а-я]*\s+(?:поесть|для ужина)')
_SELECT = re.compile(r'(?i)посовет|порекоменд|подбер|подбери|сходить|поесть|поужинать|пообедать|позавтракать|недорог|д[её]шев|бюджет|в центре|найди|найти|сравни|вариант')
_CONTINUE = re.compile(r'(?i)^(?:а\s+)?(?:нет|не[, ]|это|эти|там|они|ещ[её]|подробнее|продолж|поищи|посмотри|ты посмотри)|больше\s+(?:вариант|источник)|побольше|не\s+бюджет|слишком\s+дорог')

def selection_request(query, history=()):
    from app.services.request_intent import forbids_web
    text = (query or '').strip()
    if forbids_web(text):
        return ''
    if re.search(r'новая тема|другой вопрос|сменим тему', text, re.I):
        return text if _VENUE.search(text) and _SELECT.search(text) else ''
    if _VENUE.search(text) and _SELECT.search(text):
        return text
    if len(text)>800 or not _CONTINUE.search(text):
        return ''
    previous=[]
    for item in list(history or [])[-16:]:
        role=item.get('role') if isinstance(item,dict) else getattr(item,'role',None)
        content=item.get('content') if isinstance(item,dict) else getattr(item,'content','')
        if role=='user' and isinstance(content,str) and content.strip()!=text:
            previous.append(content[:2000])
    for i in range(len(previous)-1,-1,-1):
        if _VENUE.search(previous[i]) and _SELECT.search(previous[i]):
            return '\n'.join(previous[i:]+[text])[-7000:]
        if not _CONTINUE.search(previous[i]) or re.search(r'новая тема|другой вопрос|сменим тему',previous[i],re.I):
            break
    return ''

def configure_budget():
    from app.services.search_budget import current_search_budget
    budget=current_search_budget.get()
    if budget is not None:
        budget.searches=max(budget.searches,8)
        budget.reads=max(budget.reads,18)
