def set_run(run, *, size=11, bold=False, color=BLACK, font="Calibri"):
    run.bold = bold
    run.font.size = Pt(size)
    run.font.color.rgb = color
    run.font.name = font
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn("w:eastAsia"), font)
    rFonts.set(qn("w:cs"), font)


def add_text(p, text, **kwargs):
    run = p.add_run(text)
    set_run(run, **kwargs)
    return run


def style_paragraph(p, *, after=8, before=0, line=1.15, align=WD_ALIGN_PARAGRAPH.LEFT):
    p.alignment = align
    pf = p.paragraph_format
    pf.space_after = Pt(after)
    pf.space_before = Pt(before)
    pf.line_spacing_rule = WD_LINE_SPACING.MULTIPLE
    pf.line_spacing = line
    return p


def heading(doc, text, level=1):
    p = doc.add_paragraph()
    style_paragraph(p, after=8, before=18 if level == 1 else 12, line=1.2)
    add_text(p, text, size=18 if level == 1 else 14, bold=True, color=NAVY if level == 1 else TEAL)
    return p


def para(doc, text, *, after=8):
    p = doc.add_paragraph()
    style_paragraph(p, after=after)
    add_text(p, text, size=11)
    return p


def bullet(doc, text, *, level=0):
    p = doc.add_paragraph(style="List Bullet")
    p.clear()
    style_paragraph(p, after=4, before=0, line=1.15)
    p.paragraph_format.left_indent = Cm(1.25 + level * 0.6)
    add_text(p, text, size=11)
    return p


def numbered(doc, text):
    p = doc.add_paragraph(style="List Number")
    p.clear()
    style_paragraph(p, after=4, before=0, line=1.15)
    p.paragraph_format.left_indent = Cm(1.25)
    add_text(p, text, size=11)
    return p


def note(doc, text):
    p = doc.add_paragraph()
    style_paragraph(p, after=10, before=2)
    add_text(p, "Важно. ", size=11, bold=True, color=TEAL)
    add_text(p, text, size=11)
    return p


def fill_cell(cell, text, *, bold=False, size=10, color=BLACK, fill=None):
    cell.text = ""
    p = cell.paragraphs[0]
    style_paragraph(p, after=2, before=2, line=1.1)
    add_text(p, text, size=size, bold=bold, color=color)
    if fill:
        tc = cell._tc
        tcPr = tc.get_or_add_tcPr()
        shd = tcPr.makeelement(
            qn("w:shd"),
            {
                qn("w:val"): "clear",
                qn("w:color"): "auto",
                qn("w:fill"): fill,
            },
        )
        tcPr.append(shd)


def set_cell_margins(cell, **kwargs):
    tc = cell._tc
    tcPr = tc.get_or_add_tcPr()
    tcMar = tcPr.makeelement(qn("w:tcMar"), {})
    for edge, value in kwargs.items():
        node = tcMar.makeelement(qn(f"w:{edge}"), {qn("w:w"): str(value), qn("w:type"): "dxa"})
        tcMar.append(node)
    tcPr.append(tcMar)


def add_table(doc, headers, rows, col_widths=None):
    table = doc.add_table(rows=1 + len(rows), cols=len(headers))
    table.style = "Table Grid"
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    for i, h in enumerate(headers):
        cell = table.rows[0].cells[i]
        fill_cell(cell, h, bold=True, size=10, color=RGBColor(0xFF, 0xFF, 0xFF), fill="0E6E7A")
        set_cell_margins(cell, top="60", bottom="60", left="80", right="80")
    for r_i, row in enumerate(rows):
        bg = "F4F8F9" if r_i % 2 == 0 else "FFFFFF"
        for c_i, val in enumerate(row):
            cell = table.rows[r_i + 1].cells[c_i]
            fill_cell(cell, val, size=10, fill=bg)
            set_cell_margins(cell, top="50", bottom="50", left="80", right="80")
    if col_widths:
        table.autofit = False
        for row in table.rows:
            for i, w in enumerate(col_widths):
                row.cells[i].width = Cm(w)
    doc.add_paragraph()
    return table


